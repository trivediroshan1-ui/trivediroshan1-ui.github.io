"""Privileged access lab, round 4: check the locked guesses, then compare them with the measured values.

    python3 pam-lab/evidence/round4/round4.py --verify
    python3 pam-lab/evidence/round4/round4.py --aggregate DIR [--out pam-lab/evidence]

DIR holds the r4-<case>-<setting>.json files written by run_case.py, one per job in the workflow.
Writes results-round-4.json and RESULTS-round-4.md. A cell that errored is shown as "not measured" and the
row is not scored, so a harness failure can never count as a match or a miss. Standard library only.
"""
import argparse, glob, hashlib, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
GUESS_FILE = os.path.join(HERE, "..", "guesses", "guesses-round-4.md")
EXPECTED_SHA = "0a7cac425ed7d3b6a265e56dc69880eb130e6ab72cd8cd95b7be3823b4cb2381"
ORDER = ["none", "all", "off_a", "off_b", "off_c"]
LABEL = {"none": "no controls", "all": "all", "off_a": "off a", "off_b": "off b", "off_c": "off c"}
JOINT = [("PA-R4-01", "online check and session logout both off", 60), ("PA-R4-04", "group re-read and session end both off", 5)]


def verify():
    data = open(GUESS_FILE, "rb").read()
    sha = hashlib.sha256(data).hexdigest()
    if sha != EXPECTED_SHA:
        sys.exit("The guess file has changed since it was locked (sha256 %s). Not running." % sha)
    print("Guess file hash OK.")
    return data.decode("utf-8")


def parse(text):
    rows = {}
    for line in text.splitlines():
        m = re.match(r"\|\s*(PA-R4-\d\d)\s*\|([^|]*)\|\s*(-?\d+)\s*\|\s*(-?\d+)\s*\|\s*(-?\d+)\s*\|\s*(-?\d+)\s*\|\s*(-?\d+)\s*\|", line)
        if m:
            rows[m.group(1)] = (m.group(2).strip(), [int(m.group(i)) for i in range(3, 8)])
    return rows


def aggregate(src, out):
    guesses = parse(verify())
    got = {}
    versions = {}
    errors = []
    for p in sorted(glob.glob(os.path.join(src, "**", "r4-*.json"), recursive=True)):
        r = json.load(open(p))
        got[(r["id"], r["setting"])] = r
        versions.update(r.get("versions") or {})
        if r.get("error"):
            errors.append("%s %s: %s" % (r["id"], r["setting"], r["error"].splitlines()[0][:200]))
    rows, matched, scored = [], 0, 0
    for cid in sorted(guesses):
        label, g = guesses[cid]
        model = [got.get((cid, s), {}).get("value") for s in ORDER]
        complete = all(v is not None for v in model)
        diffs = [LABEL[s] for s, v, gv in zip(ORDER, model, g) if v is not None and v != gv]
        noticed = [s[-1] for k, s in enumerate(ORDER) if k > 1 and complete and model[k] != model[1]] if complete else []
        if complete:
            scored += 1
            matched += not diffs
        rows.append({"id": cid, "counted": label, "guess": g, "measured": model, "complete": complete,
                     "mismatch": diffs, "noticed": noticed})
    joint = []
    for cid, what, expect in JOINT:
        v = got.get((cid, "joint"), {}).get("value")
        joint.append({"id": cid, "check": what, "guess": expect, "measured": v, "match": v == expect if v is not None else None})
    summary = {"rows": len(rows), "scored": scored, "matched": matched,
               "joint_matched": sum(1 for j in joint if j["match"]), "joint_scored": sum(1 for j in joint if j["match"] is not None),
               "errors": len(errors)}
    res = {"guess_file": "guesses/guesses-round-4.md", "sha256": EXPECTED_SHA, "versions": versions, "rows": rows,
           "joint": joint, "errors": errors, "summary": summary,
           "runs": {"%s %s" % k: {"value": v.get("value"), "error": v.get("error"), "seconds": v.get("seconds"), "log": v.get("log")} for k, v in sorted(got.items())}}
    os.makedirs(out, exist_ok=True)
    json.dump(res, open(os.path.join(out, "results-round-4.json"), "w"), indent=1)
    show = lambda v: "not measured" if v is None else str(v)
    md = ["# Results: Privileged access lab, round 4 (real software)", "",
          "Generated by `round4/round4.py` from the workflow's measurements. Guesses: `guesses/guesses-round-4.md`, sha256 %s." % EXPECTED_SHA,
          "Measured on real open-source software in GitHub Actions. A row is scored only when all five settings were measured.", "",
          "Rows matched: %d of %d scored (%d rows). Joint checks matched: %d of %d. Cells with a harness error: %d." % (
              matched, scored, len(rows), summary["joint_matched"], summary["joint_scored"], len(errors)), "",
          "| ID | Counted | Guess (none, all, off a, off b, off c) | Measured | Mismatch (column that differs) | Controls noticed |", "|---|---|---|---|---|---|"]
    for r in rows:
        md.append("| %s | %s | %s | %s | %s | %s |" % (r["id"], r["counted"], r["guess"], "[" + ", ".join(show(v) for v in r["measured"]) + "]",
                                                     ", ".join(r["mismatch"]) or ("match" if r["complete"] else "not scored"),
                                                     ", ".join(r["noticed"]) or "none"))
    md += ["", "## Joint checks", "", "| ID | Check | Guess | Measured | Match |", "|---|---|---|---|---|"]
    for j in joint:
        md.append("| %s | %s | %s | %s | %s |" % (j["id"], j["check"], j["guess"], show(j["measured"]),
                                                {True: "yes", False: "no", None: "not measured"}[j["match"]]))
    md += ["", "## Software measured", ""] + ["- %s: `%s`" % (k, v) for k, v in sorted(versions.items())]
    if errors:
        md += ["", "## Harness errors (not results)", ""] + ["- " + e for e in errors]
    open(os.path.join(out, "RESULTS-round-4.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--verify", action="store_true")
    ap.add_argument("--aggregate")
    ap.add_argument("--out", default=os.path.join(HERE, ".."))
    a = ap.parse_args()
    if a.verify:
        verify()
    if a.aggregate:
        aggregate(a.aggregate, a.out)
